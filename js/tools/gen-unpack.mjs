// Generates js/src/unpack.gen.js: width-specialized, fully unrolled unpackers for one Parquet
// DELTA_BINARY_PACKED miniblock of 32 values (bit width 0…32, LSB-first bit order).
// Static source on purpose: the library must run under a CSP that forbids eval/new Function.
//   node js/tools/gen-unpack.mjs
import { writeFileSync } from 'node:fs';

const N = 32;

// One unpacker per width: reads w little-endian 32-bit words starting at byte p (any alignment),
// writes 32 prefix-summed values to O[o…o+31], returns the running value.
// acc + md + v is exact in a double (|acc|, |md| < 2^34, v < 2^32); |0 wraps to int32 like the writer.
function gen(w, load) {
  const L = [];
  for (let k = 0; k < w; k++) L.push(`const w${k} = ${load(k)};`);
  const mask = w === 32 ? null : (2 ** w - 1) >>> 0;
  for (let j = 0; j < N; j++) {
    let v = '0';
    if (w === 32) v = `(w${j} >>> 0)`;
    else if (w > 0) {
      const bit = j * w, k = bit >>> 5, sh = bit & 31;
      let e = sh === 0 ? `w${k}` : `(w${k} >>> ${sh})`;
      if (sh + w > 32) e = `(${e} | (w${k + 1} << ${32 - sh}))`;
      v = sh + w === 32 ? e : `(${e} & ${mask})`;
    }
    L.push(w === 0 ? `O[o + ${j}] = acc = (acc + md) | 0;` : `O[o + ${j}] = acc = (acc + md + ${v}) | 0;`);
  }
  L.push('return acc;');
  return L.map((l) => '  ' + l).join('\n');
}

// DataView reads (unaligned, little-endian). Measured against assembling words from four byte
// loads: 4.3 vs 2.7 GB/s raw-equivalent on the bench terrain, so only this variant ships.
const variants = {
  DELTA32: { args: 'dv, p, O, o, acc, md', load: (k) => `dv.getInt32(p + ${4 * k}, true)` },
};

let out = '// GENERATED by js/tools/gen-unpack.mjs — do not edit.\n';
out += '// Unpack one DELTA_BINARY_PACKED miniblock of 32 values at bit width w (the array index).\n';
for (const [name, { args, load }] of Object.entries(variants)) {
  out += `\nexport const ${name} = [\n`;
  for (let w = 0; w <= 32; w++) out += `function ${name.toLowerCase()}_${w}(${args}) {\n${gen(w, load)}\n},\n`;
  out += '];\n';
}
writeFileSync(new URL('../src/unpack.gen.js', import.meta.url), out);
console.log(`wrote unpack.gen.js (${(out.length / 1024).toFixed(0)} KB)`);
